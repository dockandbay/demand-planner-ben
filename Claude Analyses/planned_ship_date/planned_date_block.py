"""Builds the planned-ship-date block that is appended to each channel's Fulfil order_import function.

The block runs inside Fulfil's restricted function runtime, so it uses only plain loops, ifs, dict/list
access, str() and the datetime module: no any/all/min/max/sum/sorted/enumerate/zip/map/filter and no named
exception classes (see memory fulfil-functions-runtime). It never adds an order exception: on any error it
leaves dates as imported and notes the error in order metadata.

Rule (Ben, 22-Oct-26): planned ship date = today in the warehouse's local time + N business days,
N = 1 retail (personalised too: +5 held shipments back from the 3PL, changed 26-Oct-26), 3 wholesale. Weekends and the warehouse
country's public holidays are skipped; an order placed on a non-business day counts from the next one.
A later date already on a line, or an order-level shipping_start_date (preorder / future ship date), is kept.
"""

BLOCK = '''
    # --- Planned ship date (%(label)s) ---
    # Generated by Claude Analyses/planned_ship_date/planned_date_block.py; edit there, not here.
    # +%(retail)s business day(s) retail, +%(personalised)s if any line is personalised, +%(wholesale_days)s wholesale
    # (the larger applies), counted from today in %(tz)s, skipping weekends and %(holidays)s holidays.
    # Never blocks the order: on any error dates stay as imported and the error is noted in metadata.
    try:
        from datetime import datetime, date, timedelta

        PSD_TZ = "%(tz)s"
        PSD_HOLIDAYS = "%(holidays)s"
        PSD_RETAIL = %(retail)s
        PSD_PERSONALISED = %(personalised)s
        PSD_WHOLESALE = %(wholesale)s

        def psd_nth_weekday(year, month, weekday, n):
            d = date(year, month, 1)
            while d.weekday() != weekday:
                d = d + timedelta(days=1)
            return d + timedelta(days=7 * (n - 1))

        def psd_last_weekday(year, month, weekday):
            if month == 12:
                d = date(year, 12, 31)
            else:
                d = date(year, month + 1, 1) - timedelta(days=1)
            while d.weekday() != weekday:
                d = d - timedelta(days=1)
            return d

        def psd_easter(year):
            a = year %% 19
            b = year // 100
            c = year %% 100
            d = b // 4
            e = b %% 4
            f = (b + 8) // 25
            g = (b - f + 1) // 3
            h = (19 * a + b - d - g + 15) %% 30
            i = c // 4
            k = c %% 4
            l = (32 + 2 * e + 2 * i - h - k) %% 7
            m = (a + 11 * h + 22 * l) // 451
            month = (h + l - 7 * m + 114) // 31
            day = ((h + l - 7 * m + 114) %% 31) + 1
            return date(year, month, day)

        def psd_next_weekday_if_weekend(d):
            while d.weekday() >= 5:
                d = d + timedelta(days=1)
            return d

        def psd_holidays(year):
            hol = {}
            easter = psd_easter(year)
            if PSD_HOLIDAYS == "England":
                hol[psd_next_weekday_if_weekend(date(year, 1, 1))] = 1
                hol[easter - timedelta(days=2)] = 1
                hol[easter + timedelta(days=1)] = 1
                hol[psd_nth_weekday(year, 5, 0, 1)] = 1
                hol[psd_last_weekday(year, 5, 0)] = 1
                hol[psd_last_weekday(year, 8, 0)] = 1
                xmas = date(year, 12, 25)
                if xmas.weekday() == 5:
                    hol[date(year, 12, 27)] = 1
                    hol[date(year, 12, 28)] = 1
                elif xmas.weekday() == 6:
                    hol[date(year, 12, 26)] = 1
                    hol[date(year, 12, 27)] = 1
                elif xmas.weekday() == 4:
                    hol[xmas] = 1
                    hol[date(year, 12, 28)] = 1
                else:
                    hol[xmas] = 1
                    hol[date(year, 12, 26)] = 1
            elif PSD_HOLIDAYS == "US carriers":
                for fixed in (date(year, 1, 1), date(year, 7, 4), date(year, 12, 25)):
                    if fixed.weekday() == 5:
                        hol[fixed - timedelta(days=1)] = 1
                    elif fixed.weekday() == 6:
                        hol[fixed + timedelta(days=1)] = 1
                    else:
                        hol[fixed] = 1
                hol[psd_last_weekday(year, 5, 0)] = 1
                hol[psd_nth_weekday(year, 9, 0, 1)] = 1
                hol[psd_nth_weekday(year, 11, 3, 4)] = 1
            elif PSD_HOLIDAYS == "AU NSW":
                hol[psd_next_weekday_if_weekend(date(year, 1, 1))] = 1
                hol[psd_next_weekday_if_weekend(date(year, 1, 26))] = 1
                hol[easter - timedelta(days=2)] = 1
                hol[easter + timedelta(days=1)] = 1
                hol[date(year, 4, 25)] = 1
                hol[psd_nth_weekday(year, 6, 0, 2)] = 1
                hol[psd_nth_weekday(year, 10, 0, 1)] = 1
                xmas = date(year, 12, 25)
                if xmas.weekday() == 5:
                    hol[date(year, 12, 27)] = 1
                    hol[date(year, 12, 28)] = 1
                elif xmas.weekday() == 6:
                    hol[date(year, 12, 26)] = 1
                    hol[date(year, 12, 27)] = 1
                elif xmas.weekday() == 4:
                    hol[xmas] = 1
                    hol[date(year, 12, 28)] = 1
                else:
                    hol[xmas] = 1
                    hol[date(year, 12, 26)] = 1
            elif PSD_HOLIDAYS == "Netherlands":
                hol[date(year, 1, 1)] = 1
                hol[easter - timedelta(days=2)] = 1
                hol[easter + timedelta(days=1)] = 1
                kings = date(year, 4, 27)
                if kings.weekday() == 6:
                    kings = date(year, 4, 26)
                hol[kings] = 1
                hol[easter + timedelta(days=39)] = 1
                hol[easter + timedelta(days=50)] = 1
                hol[date(year, 12, 25)] = 1
                hol[date(year, 12, 26)] = 1
            elif PSD_HOLIDAYS == "Germany":
                hol[date(year, 1, 1)] = 1
                hol[easter - timedelta(days=2)] = 1
                hol[easter + timedelta(days=1)] = 1
                hol[date(year, 5, 1)] = 1
                hol[easter + timedelta(days=39)] = 1
                hol[easter + timedelta(days=50)] = 1
                hol[date(year, 10, 3)] = 1
                hol[date(year, 12, 25)] = 1
                hol[date(year, 12, 26)] = 1
            return hol

        def psd_local_now():
            now = datetime.utcnow()
            y = now.year
            if PSD_TZ == "Europe/London" or PSD_TZ == "Europe/Amsterdam" or PSD_TZ == "Europe/Berlin":
                base = 0
                if PSD_TZ != "Europe/London":
                    base = 1
                start = datetime.combine(psd_last_weekday(y, 3, 6), datetime.min.time()) + timedelta(hours=1)
                end = datetime.combine(psd_last_weekday(y, 10, 6), datetime.min.time()) + timedelta(hours=1)
                if start <= now and now < end:
                    return now + timedelta(hours=base + 1)
                return now + timedelta(hours=base)
            if PSD_TZ == "America/Chicago":
                start = datetime.combine(psd_nth_weekday(y, 3, 6, 2), datetime.min.time()) + timedelta(hours=8)
                end = datetime.combine(psd_nth_weekday(y, 11, 6, 1), datetime.min.time()) + timedelta(hours=7)
                if start <= now and now < end:
                    return now - timedelta(hours=5)
                return now - timedelta(hours=6)
            if PSD_TZ == "Australia/Sydney":
                end = datetime.combine(psd_nth_weekday(y, 4, 6, 1), datetime.min.time()) - timedelta(hours=8)
                start = datetime.combine(psd_nth_weekday(y, 10, 6, 1), datetime.min.time()) - timedelta(hours=8)
                if now < end or start <= now:
                    return now + timedelta(hours=11)
                return now + timedelta(hours=10)
            return now

        def psd_is_business_day(d):
            if d.weekday() >= 5:
                return False
            return d not in psd_holidays(d.year)

        def psd_add_business_days(start, n):
            d = start
            if not psd_is_business_day(d):
                n = n + 1
            while n > 0:
                d = d + timedelta(days=1)
                if psd_is_business_day(d):
                    n = n - 1
            return d

        if not order_data.get("shipping_start_date"):
            psd_lines = order_data.get("sale_lines") or []
            psd_days = PSD_RETAIL
            if PSD_WHOLESALE:
                psd_days = %(wholesale_days)s
            for psd_line in psd_lines:
                for psd_opt in (psd_line.get("product_options") or []):
                    if psd_opt.get("code") == "personalisation" and PSD_PERSONALISED > psd_days:
                        psd_days = PSD_PERSONALISED
            psd_target = psd_add_business_days(psd_local_now().date(), psd_days)
            for psd_line in psd_lines:
                psd_existing = psd_line.get("shipping_date")
                if psd_existing:
                    try:
                        if date.fromisoformat(str(psd_existing)[:10]) > psd_target:
                            continue
                    except Exception:
                        pass
                psd_line["shipping_date"] = psd_target.isoformat()
    except Exception as psd_exc:
        psd_meta = order_data.get("metadata") or {}
        psd_meta["planned_ship_date_error"] = str(psd_exc)[:200]
        order_data["metadata"] = psd_meta
'''

# Per live function: (label, tz, holiday set, wholesale?)
CONFIGS = {
    1:  {"label": "US retail", "tz": "America/Chicago", "holidays": "US carriers", "wholesale": False},
    3:  {"label": "AU retail", "tz": "Australia/Sydney", "holidays": "AU NSW", "wholesale": False},
    36: {"label": "EU wholesale", "tz": "Europe/Berlin", "holidays": "Germany", "wholesale": True},  # iFulfillment = Germany (Ben 22-Oct); national holidays only
    37: {"label": "US wholesale", "tz": "America/Chicago", "holidays": "US carriers", "wholesale": True},
    44: {"label": "UK wholesale", "tz": "Europe/London", "holidays": "England", "wholesale": True},
}


def block(cfg, retail=1, personalised=1, wholesale_days=3):
    return BLOCK % {"label": cfg["label"], "tz": cfg["tz"], "holidays": cfg["holidays"], "retail": retail,
                    "personalised": personalised, "wholesale": "True" if cfg["wholesale"] else "False",
                    "wholesale_days": wholesale_days}


def inject(code, cfg):
    """Insert the block before the function's final `return order_data`."""
    marker = "\n    return order_data"
    i = code.rfind(marker)
    if i < 0:
        raise ValueError("no final 'return order_data' found")
    return code[:i] + "\n" + block(cfg).rstrip("\n") + "\n" + code[i:]
