-- 399_ilg_stock_rebaseline.sql (v28.553, Ben 28-Oct-26): ILG "DOCKBAY Daily Stock Report" from the ops@ inbox into Manage 3PL ▸ UK, split by
-- owner (DOCKBAY = UK ILG, DOCKFBA = UK Non GRS / ILG - FBA, DOCKVENDOR = UK Vendor / John Lewis), compared with Fulfil, and a ticked
-- rebaseline (Fulfil stock count per ILG warehouse) that n8n writes on the user's request. Additive.
CREATE TABLE IF NOT EXISTS planner.ilg_stock_reports (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id    text,                          -- Gmail message id (ops@); null for a manual upload
  filename      text NOT NULL,
  report_at     timestamptz NOT NULL,          -- from the file name (DOCKBAY_DAILYSTOCKREPORT_yyyymmdd_hhmm), Europe/London
  received_at   timestamptz,                   -- Gmail internal date
  source        text NOT NULL DEFAULT 'gmail' CHECK (source IN ('gmail','upload')),
  rows          jsonb NOT NULL,                -- [{owner, sku, description, barcode, status, physical, free}]
  imported_at   timestamptz NOT NULL DEFAULT now(),
  imported_by   text
);
CREATE UNIQUE INDEX IF NOT EXISTS ilg_stock_reports_msg_uq ON planner.ilg_stock_reports (message_id) WHERE message_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ilg_stock_reports_at_ix ON planner.ilg_stock_reports (report_at DESC);
-- One rebaseline = one Fulfil stock count for one ILG warehouse. HORIZON creates it 'pending' when a user ticks SKUs and presses Rebaseline;
-- the n8n stocktake flow writes the count (guarded write), confirms it, reads it back and posts the result ('done' / 'error').
CREATE TABLE IF NOT EXISTS planner.ilg_rebaseline_batches (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id        bigint REFERENCES planner.ilg_stock_reports(id),
  pool             text NOT NULL CHECK (pool IN ('UK','UK_NG','UK_VD')),
  warehouse_id     int  NOT NULL,              -- Fulfil warehouse (206 UK ILG, 215 ILG - FBA, 214 ILG - VENDOR)
  location_id      int  NOT NULL,              -- the counted Storage Zone (205 / 213 / 210)
  lost_found_id    int  NOT NULL DEFAULT 10,   -- adjustment location (Lost and Found)
  lines            jsonb NOT NULL,             -- [{sku, product_id, report_qty, fulfil_at_report, moved_since, storage_now, set_to}]
  status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','done','error','cancelled')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  created_by       text,
  sent_at          timestamptz,
  done_at          timestamptz,
  fulfil_count_id  int,
  fulfil_number    text,
  result           jsonb,                      -- n8n read-back (lines with expected / counted / difference)
  error            text
);
CREATE INDEX IF NOT EXISTS ilg_rebaseline_status_ix ON planner.ilg_rebaseline_batches (status, created_at);
REVOKE ALL ON planner.ilg_stock_reports, planner.ilg_rebaseline_batches FROM anon, authenticated;
