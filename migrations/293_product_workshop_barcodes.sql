-- 293_product_workshop_barcodes.sql
-- Product Workshop Barcodes (Ben): a fixed pool of REAL GS1 EAN-13 barcodes set aside for the design/product team.
-- Seeded from the '100 barcodes for design from the 100k' GS1 block (106 codes, valid check digits). A code is
-- claimed by a product size (PRODUCT ▸ product detail ▸ Sizes) and then shows as 'assigned'. No allocation logic beyond
-- claim/release — the pool is finite and hand-curated. Print/preview is client-side (reuses the barcode-gen renderer).
CREATE TABLE IF NOT EXISTS planner.product_workshop_barcodes (
  barcode          text PRIMARY KEY,             -- the EAN-13 value (13 digits, real GS1)
  seq              int,                           -- 1..N order in the seed block, for stable display
  source           text DEFAULT 'GS1 100k — design 100',
  status           text NOT NULL DEFAULT 'free', -- 'free' | 'assigned'
  assigned_size_id bigint,                        -- planner.product_dev_sizes(id) it was claimed by
  assigned_ref     text,                          -- product_dev_items.ref (the product)
  assigned_sku     text,                          -- the working OR real sku it backs
  assigned_by      text,
  assigned_at      timestamptz,
  created_at       timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS product_workshop_barcodes_status ON planner.product_workshop_barcodes (status);
CREATE INDEX IF NOT EXISTS product_workshop_barcodes_size   ON planner.product_workshop_barcodes (assigned_size_id);

