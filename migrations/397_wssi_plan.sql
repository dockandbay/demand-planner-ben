-- 397_wssi_plan.sql (v28.548, Ben 28-Oct-26, WSSI phases 3 and 4 from Kathryn's template). Additive.
-- Phase 3, plan layer: Abi's signed-off plan by month x market x channel x category group: sales £, sales units, closing stock units. Edited as a
-- draft; an admin locks it as version n (dated, read only); a new draft starts from the latest locked version. WSSI uses the latest locked version.
CREATE TABLE IF NOT EXISTS planner.wssi_plan_versions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fy          int     NOT NULL,                       -- financial year start (Mar fy .. Feb fy+1)
  status      text    NOT NULL CHECK (status IN ('draft','locked')),
  version     int,                                    -- 1, 2, ... once locked
  note        text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  created_by  text,
  locked_at   timestamptz,
  locked_by   text
);
CREATE UNIQUE INDEX IF NOT EXISTS wssi_plan_versions_one_draft ON planner.wssi_plan_versions (fy) WHERE status = 'draft';
CREATE TABLE IF NOT EXISTS planner.wssi_plan_cells (
  version_id  bigint  NOT NULL REFERENCES planner.wssi_plan_versions(id) ON DELETE CASCADE,
  month       date    NOT NULL,
  market      text    NOT NULL,
  channel     text    NOT NULL,
  cgroup      text    NOT NULL,
  measure     text    NOT NULL CHECK (measure IN ('sales','units','close')),   -- sales £ (ex VAT), sales units, closing stock units
  value       numeric NOT NULL,
  PRIMARY KEY (version_id, month, market, channel, cgroup, measure)
);
-- Phase 4: live overrides (not versioned; blank = the system value): forecast sales units (open months) and target closing units.
CREATE TABLE IF NOT EXISTS planner.wssi_overrides (
  month       date    NOT NULL,
  market      text    NOT NULL,
  channel     text    NOT NULL,
  cgroup      text    NOT NULL,
  measure     text    NOT NULL CHECK (measure IN ('fc_units','target_units')),
  value       numeric NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text,
  PRIMARY KEY (month, market, channel, cgroup, measure)
);
-- Phase 4: the forecast as it stood at the end of each month (kept up to date while the month is open, frozen once actuals replace it), so
-- WSSI can show actual vs forecast for closed months.
CREATE TABLE IF NOT EXISTS planner.wssi_fc_snapshot (
  month       date    NOT NULL,
  market      text    NOT NULL,
  channel     text    NOT NULL,
  cgroup      text    NOT NULL,
  units       numeric NOT NULL,
  sales       numeric NOT NULL,
  taken_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (month, market, channel, cgroup)
);
REVOKE ALL ON planner.wssi_plan_versions, planner.wssi_plan_cells, planner.wssi_overrides, planner.wssi_fc_snapshot FROM anon, authenticated;
