-- 393_product_size_library.sql (v28.520, Ben 27-Oct-26): "existing products should have a default size user can select, or add new custom
-- sizes" + "should be a searchable filter selection box". A size library (seeded from Ben's SIZE-WORKING.csv: code, global size description,
-- UK product length / width / height in cm), editable in PRODUCT > Config > Sizes. Picking a library size on a product fills its label and
-- dimensions (cm only: the inch part of the CSV labels is dropped). A product size can still be a custom label. Additive.
CREATE TABLE IF NOT EXISTS planner.product_size_library (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text NOT NULL,
  label       text NOT NULL,
  length_cm   numeric,
  width_cm    numeric,
  height_cm   numeric,
  active      boolean NOT NULL DEFAULT true,
  sort        integer,
  updated_by  text,
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS product_size_library_code_uq ON planner.product_size_library (upper(code));
REVOKE ALL ON planner.product_size_library FROM anon, authenticated;
ALTER TABLE planner.product_dev_sizes ADD COLUMN IF NOT EXISTS length_cm numeric;
ALTER TABLE planner.product_dev_sizes ADD COLUMN IF NOT EXISTS width_cm numeric;
ALTER TABLE planner.product_dev_sizes ADD COLUMN IF NOT EXISTS height_cm numeric;
ALTER TABLE planner.product_dev_sizes ADD COLUMN IF NOT EXISTS library_code text;   -- the library size it was picked from (blank = custom)
