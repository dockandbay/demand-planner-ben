-- v28.327 (Ben 13-Oct-26): SUPPLY > PAYMENTS > Other Payments > Create sample bills. Additive and idempotent.
-- A supplier's courier / sample invoice (typed in, or seeded from the FedEx / DHL template .xlsx) becomes ONE Other payment per
-- document: one Fulfil DRAFT supplier invoice per Fulfil PO (a line per charge, landed cost by value, also draft), and one Xero bill
-- per org for everything else (sample lines by purpose; pre-Fulfil PO lines on 302 freight / 313 duty). The Other payment carries
-- the same reference as its document (XR-FEDEX-2026-02, or -A / -B / -C when one invoice makes several documents).

CREATE TABLE IF NOT EXISTS planner.sample_bills (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_base      text NOT NULL,
  supplier_name text,
  invoice_date  date,
  due_date      date,
  currency      text NOT NULL DEFAULT 'USD',
  fx_rate       numeric(12,5),              -- source rate (CNY per USD) as printed on the file, for the record
  source_file   text,
  sheet_total   numeric(14,2),
  total         numeric(14,2),
  created_by    text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS planner.sample_bill_lines (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_id          bigint NOT NULL REFERENCES planner.sample_bills(id) ON DELETE CASCADE,
  seq              int NOT NULL,
  ship_date        date,
  tracking         text,
  charge           text NOT NULL DEFAULT 'freight',    -- freight | duty | tax | product | other
  description      text,
  ship_to          text,                               -- US / UK / AU / EU / ...
  sample_type      text,                               -- as on the file (Product Development, Sales Sample, ...)
  requested_by     text,
  recipient        text,
  pcs              text,
  po               text,                               -- HORIZON PO as typed / resolved
  link_type        text NOT NULL,                      -- fulfil | xero
  fulfil_po_id     bigint,
  fulfil_po_number text,
  fulfil_company   int,                                -- 1 UK / 3 AU
  fulfil_product   text,                               -- LANDED-FREIGHT / LANDED-IMPORT-DUTY / LANDED-IMPORT-TAX-UK|AU|EU
  xero_org         text,                               -- uk | au
  xero_account     text,
  sample_ref       text,                               -- SR-n or a product sample ref
  amount_src       numeric(14,2),                      -- amount in the file's source currency (CNY), if given
  amount           numeric(14,2) NOT NULL,
  doc_key          text,                               -- fulfil:<po id> | xero:<org>
  other_payment_id bigint
);
CREATE INDEX IF NOT EXISTS sample_bill_lines_bill_idx ON planner.sample_bill_lines (bill_id);
CREATE INDEX IF NOT EXISTS sample_bill_lines_op_idx ON planner.sample_bill_lines (other_payment_id);

-- The Other payment knows its document once pushed: system, id, number, link, state.
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS sample_bill_id bigint;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_system text;          -- fulfil | xero
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_org text;             -- uk | au
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_id text;              -- Fulfil account.invoice id / Xero InvoiceID
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_number text;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_url text;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_status text;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_landed_cost_id text;  -- Fulfil account.landed_cost id (draft)
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_error text;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_pushed_at timestamptz;
ALTER TABLE planner.deposits ADD COLUMN IF NOT EXISTS doc_pushed_by text;
CREATE INDEX IF NOT EXISTS deposits_sample_bill_idx ON planner.deposits (sample_bill_id) WHERE sample_bill_id IS NOT NULL;
