-- NEXT pays many TS invoices in one BGC payment. HORIZON checks the pasted remittance against open Xero invoices, then on confirm
-- (a) Receive Money in the bank for the full amount to the key account's clearing account and (b) one Xero batch payment from that
-- clearing account paying each remitted invoice. Anything NEXT deducted (SL debit notes) stays in the clearing account until a credit note
-- clears it. Config per key account is editable here (help text = the (i) tooltip steps). Additive.
CREATE TABLE IF NOT EXISTS planner.accounts_ka_config (
  ka_key              text PRIMARY KEY,                 -- 'NEXT'
  org                 text NOT NULL DEFAULT 'uk' CHECK (org IN ('uk','au')),
  label               text NOT NULL,
  contact_id          text NOT NULL,                    -- Xero ContactID the invoices belong to
  contact_name        text NOT NULL,
  match_re            text NOT NULL,                    -- JavaScript regex (case-insensitive) on the bank line reference / payee
  bank_account_id     text NOT NULL,                    -- Xero bank account the payment lands in
  bank_account_name   text NOT NULL,
  clearing_code       text NOT NULL,
  clearing_account_id text NOT NULL,
  clearing_name       text NOT NULL,
  invoice_re          text NOT NULL DEFAULT '^TS\d{5,}$', -- invoice numbers in the remittance
  help                text NOT NULL DEFAULT '',          -- process steps shown in the (i) tooltips (one step per line)
  enabled             boolean NOT NULL DEFAULT true,
  updated_at          timestamptz NOT NULL DEFAULT now(),
  updated_by          text
);
-- One row per bank line posted. The partial unique index stops a second post for the same line (re-click, two tabs).
CREATE TABLE IF NOT EXISTS planner.accounts_ka_receipts (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ka_key           text NOT NULL REFERENCES planner.accounts_ka_config(ka_key),
  org              text NOT NULL,
  account_name     text NOT NULL,
  line_date        date NOT NULL,
  line_amount      numeric(14,2) NOT NULL,
  line_ref         text NOT NULL DEFAULT '',
  remittance       jsonb NOT NULL,                   -- [{invoice, amount}] as pasted
  payments         jsonb NOT NULL DEFAULT '[]',      -- [{invoice, invoice_id, po, due_before, amount, part}]
  paid_total       numeric(14,2) NOT NULL DEFAULT 0,
  unexplained      numeric(14,2) NOT NULL DEFAULT 0, -- bank amount minus paid_total: left in the clearing account
  xero_receive_id  text,
  xero_batch_id    text,
  status           text NOT NULL DEFAULT 'creating' CHECK (status IN ('creating','receive_done','created','error','dry_run')),
  error            text,
  readback         jsonb,
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS accounts_ka_receipts_line_uq ON planner.accounts_ka_receipts (ka_key, org, account_name, line_date, line_amount, line_ref)
  WHERE status IN ('creating','receive_done','created');
CREATE INDEX IF NOT EXISTS accounts_ka_receipts_ka_ix ON planner.accounts_ka_receipts (ka_key, line_date DESC);
